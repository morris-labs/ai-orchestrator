import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { makeHarness } from "../boxes/harness.js";

function write(file: string, text: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

describe("account instruction layers", () => {
  it("prepares the default Codex account and expands current global and account instructions at every start", () => {
    const h = makeHarness({ accounts: false });
    const account = h.core.accounts.create({ vendor: "codex", name: "personal" });
    const global = path.resolve(account.dir, "../../AGENTS.md");
    const source = path.join(account.dir, "instructions.md");
    expect(fs.readFileSync(source, "utf8")).toContain("@../../AGENTS.md");
    write(global, "Global working rules\n");
    write(source, "@../../AGENTS.md\nAccount working rules\n@extra.md\n");
    write(path.join(account.dir, "extra.md"), "Additional rules\n");
    const prepared = h.core.accounts.prepareAccount("codex");
    expect(prepared).toEqual({ dir: account.dir, problems: [] });
    const output = fs.readFileSync(path.join(account.dir, "AGENTS.md"), "utf8");
    expect(output).toMatch(
      /Global working rules[\s\S]*Account working rules[\s\S]*Additional rules[\s\S]*Generated/,
    );
    expect(output).toContain(source);
    expect(output).toContain(global);
    expect(output).not.toContain("@extra.md");
    write(global, "Edited global rules\n");
    h.core.accounts.prepareAccount("codex", "personal");
    expect(fs.readFileSync(path.join(account.dir, "AGENTS.md"), "utf8")).toContain(
      "Edited global rules",
    );
    expect(fs.readFileSync(source, "utf8")).toBe(
      "@../../AGENTS.md\nAccount working rules\n@extra.md\n",
    );
    h.core.close();
  });

  it("preserves imported Codex instructions as editable source before generating output", async () => {
    const h = makeHarness({ accounts: false });
    const source = h.dir("ready-codex");
    write(path.join(source, "AGENTS.md"), "Existing account rules\n");
    const account = await h.core.accounts.importFolder({
      vendor: "codex",
      name: "imported",
      from: source,
    });
    h.core.accounts.prepareAccount("codex", "imported");
    expect(fs.readFileSync(path.join(account.dir, "instructions.md"), "utf8")).toContain(
      "Existing account rules",
    );
    expect(fs.readFileSync(path.join(account.dir, "AGENTS.md"), "utf8")).toContain(
      "Existing account rules",
    );
    h.core.close();
  });

  for (const vendor of ["codex", "copilot"] as const) {
    it(`reports missing includes, loops, and depth limits while preparing ${vendor}`, () => {
      const h = makeHarness({ accounts: false });
      const account = h.core.accounts.create({ vendor, name: "limited" });
      write(path.resolve(account.dir, "../../AGENTS.md"), "Global rules\n");
      write(
        path.join(account.dir, "instructions.md"),
        "@../../AGENTS.md\nAccount rules\n@missing.md\n@a.md\n@loop.md\n",
      );
      write(path.join(account.dir, "a.md"), "Depth one\n@nested/b.md\n");
      write(path.join(account.dir, "nested/b.md"), "Depth two\n@c.md\n");
      write(path.join(account.dir, "nested/c.md"), "Depth three\n@d.md\n");
      write(path.join(account.dir, "nested/d.md"), "MUST NOT EXPAND\n");
      write(path.join(account.dir, "loop.md"), "Loop rules\n@loop.md\n");
      const prepared = h.core.accounts.prepareAccount(vendor);
      expect(prepared.problems.join("\n")).toMatch(/missing.md/);
      expect(prepared.problems.join("\n")).toMatch(/depth limit of 3/);
      expect(prepared.problems.join("\n")).toMatch(/loop skipped/);
      const output = fs.readFileSync(
        path.join(account.dir, vendor === "codex" ? "AGENTS.md" : "copilot-instructions.md"),
        "utf8",
      );
      expect(output).toContain("Global rules");
      expect(output).toContain("Account rules");
      expect(output).toContain("Depth three");
      expect(output).not.toContain("MUST NOT EXPAND");
      expect(output).not.toContain("@missing.md");
      expect(output).toContain("Generated by AI Orchestrator");
      h.core.close();
    });
  }

  it("reports unknown/default accounts clearly and leaves Claude include lines unexpanded", () => {
    const h = makeHarness({ accounts: false });
    expect(() => h.core.accounts.prepareAccount("codex")).toThrow(/No default codex account/);
    expect(() => h.core.accounts.prepareAccount("claude", "unknown")).toThrow(
      /No account claude\/unknown/,
    );
    const account = h.core.accounts.create({ vendor: "claude", name: "personal" });
    const before = fs.readFileSync(path.join(account.dir, "CLAUDE.md"), "utf8");
    expect(h.core.accounts.prepareAccount("claude")).toEqual({ dir: account.dir, problems: [] });
    expect(fs.readFileSync(path.join(account.dir, "CLAUDE.md"), "utf8")).toBe(before);
    h.core.close();
  });

  it("creates global and Claude account instructions once with global include first", () => {
    const h = makeHarness({ accounts: false });
    const first = h.core.accounts.create({ vendor: "claude", name: "personal" });
    const global = path.resolve(first.dir, "../../AGENTS.md");
    const local = path.join(first.dir, "AGENTS.md");
    const claude = path.join(first.dir, "CLAUDE.md");
    expect(fs.readFileSync(global, "utf8")).toMatch(/^<!--[^\n]+-->\n$/);
    expect(fs.readFileSync(local, "utf8")).toMatch(/^<!--[^\n]+-->\n$/);
    expect(fs.readFileSync(claude, "utf8")).toContain("@../../AGENTS.md\n@AGENTS.md");
    write(global, "Global working rules\n");
    write(local, "Account working rules\n");
    write(claude, "@../../AGENTS.md\n@AGENTS.md\n@extra.md\n");
    const second = h.core.accounts.create({ vendor: "claude", name: "work" });
    expect(path.resolve(second.dir, "../../AGENTS.md")).toBe(global);
    h.core.accounts.relink();
    expect(fs.readFileSync(global, "utf8")).toBe("Global working rules\n");
    expect(fs.readFileSync(local, "utf8")).toBe("Account working rules\n");
    expect(fs.readFileSync(claude, "utf8")).toBe("@../../AGENTS.md\n@AGENTS.md\n@extra.md\n");
    h.core.close();
  });
});
