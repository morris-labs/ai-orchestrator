// Account-owned instruction sources; includes replace host configuration links.
import fs from "node:fs";
import path from "node:path";
import type { Platform } from "@aio/contracts";

function writeMissing(file: string, text: string): void {
  try {
    fs.writeFileSync(file, text, { flag: "wx", mode: 0o600 });
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== "EEXIST") throw err;
  }
}

/** Fill missing layers without replacing instructions the owner has edited. */
export function ensureAccountInstructions(dir: string, vendor: Platform): void {
  const global = path.resolve(dir, "../../AGENTS.md");
  writeMissing(global, "<!-- Global instructions for every account. -->\n");
  if (vendor === "claude") {
    writeMissing(path.join(dir, "AGENTS.md"), "<!-- Account instructions. -->\n");
    writeMissing(
      path.join(dir, "CLAUDE.md"),
      "<!-- Includes: global instructions, then account instructions. -->\n@../../AGENTS.md\n@AGENTS.md\n",
    );
  } else {
    const source = path.join(dir, "instructions.md");
    try {
      fs.lstatSync(source);
      return;
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
    }
    const previous = path.join(dir, vendor === "codex" ? "AGENTS.md" : "copilot-instructions.md");
    let local = "<!-- Account instructions. -->\n";
    try {
      local = fs.readFileSync(previous, "utf8");
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
    }
    writeMissing(source, `@../../AGENTS.md\n\n${local}`);
  }
}

/** Expand one include-line source, bounded to three include levels. */
export function buildAccountInstructions(dir: string, vendor: "codex" | "copilot"): string[] {
  const problems: string[] = [];
  const sources = new Set<string>();
  const expand = (file: string, depth: number, chain: readonly string[]): string => {
    if (depth > 3) {
      problems.push(`Include depth limit of 3 reached: ${file}`);
      return "";
    }
    let real: string;
    let text: string;
    try {
      real = fs.realpathSync(file);
      if (chain.includes(real)) {
        problems.push(`Include loop skipped: ${file}`);
        return "";
      }
      text = fs.readFileSync(real, "utf8");
    } catch (err) {
      problems.push(`Could not include ${file}: ${(err as Error).message}`);
      return "";
    }
    sources.add(file);
    return text
      .split("\n")
      .map((line) => {
        const include = line.match(/^\s*@(.+?)\s*$/);
        if (!include) return line;
        const name = include[1]!.replace(/^"(.*)"$|^'(.*)'$/, "$1$2");
        return expand(path.resolve(path.dirname(file), name), depth + 1, [...chain, real]);
      })
      .join("\n");
  };
  const source = path.join(dir, "instructions.md");
  const expanded = expand(source, 0, []);
  const stamp = `<!-- Generated by AI Orchestrator. Edit these source files, then start again:\n${[...sources].map((file) => `  ${file}`).join("\n")}\n-->\n`;
  const output = path.join(dir, vendor === "codex" ? "AGENTS.md" : "copilot-instructions.md");
  const temp = `${output}.aio-${process.pid}-${Date.now()}.tmp`;
  try {
    fs.writeFileSync(temp, `${expanded}\n\n${stamp}`, { flag: "wx", mode: 0o600 });
    fs.renameSync(temp, output);
  } finally {
    fs.rmSync(temp, { force: true });
  }
  return problems;
}
