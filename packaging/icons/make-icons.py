#!/usr/bin/env python3
"""Regenerates the AI Orchestrator app icons.

Writes two SVG files next to this script:

- aio-boxes.svg: the Claude mark behind bars, ported from the 3.x
  the `make-jail-icon.py` script of Claude Box 3.3.5. A box is a cell you put an agent in.
- aio-review.svg: the same cell with a magnifying glass badge in the
  lower-right corner, for the review app.

The blade geometry is computed so the burst stays symmetric. Run this
script after changing anything in it, then commit the SVG files: they, not
this script, ship in the package.

Two traps for anyone editing the template:

- Keep the root element first, with no XML declaration and no comment
  before it. gdk-pixbuf picks a loader by sniffing the start of the file,
  and a header comment pushes the svg tag out of range, so GNOME shows no
  icon while other toolkits render it fine.
- Never put two hyphens in a row inside an XML comment. That makes the file
  malformed and costs you the icon without an error.
"""
import math
import pathlib

CX = CY = 128.0

# Twelve blades on a 30 degree spacing, alternating long and short, rotated
# off-axis so they don't line up with the bars in front of them.
ROTATION = 15
BLADES = [
    (ROTATION + i * 30, 88 if i % 2 == 0 else 64, 11.0 if i % 2 == 0 else 7.0)
    for i in range(12)
]

BAR_X = (56, 100, 144, 188)
BAR_W = 16

# The 3.x app palette: window #1b1c1e, border #33353a, accent #d97757.
ACCENT = "#d97757"
REVIEW_ACCENT = "#5fb3b3"


def blade_path(angle, length, halfw):
    a = math.radians(angle)
    ux, uy = math.cos(a), -math.sin(a)  # outward unit vector; SVG y grows down
    px, py = -uy, ux  # perpendicular
    tip = (CX + ux * length, CY + uy * length)
    mid = (CX + ux * length * 0.36, CY + uy * length * 0.36)
    return (
        f"M {CX:.1f} {CY:.1f} "
        f"Q {mid[0] + px * halfw:.1f} {mid[1] + py * halfw:.1f} {tip[0]:.1f} {tip[1]:.1f} "
        f"Q {mid[0] - px * halfw:.1f} {mid[1] - py * halfw:.1f} {CX:.1f} {CY:.1f} Z"
    )


def cell(comment, badge=""):
    blades = "\n    ".join(f'<path d="{blade_path(*b)}"/>' for b in BLADES)
    shadows = "\n    ".join(
        f'<rect x="{x + 4}" y="34" width="{BAR_W}" height="188" rx="8" fill="#000000" opacity="0.16"/>'
        for x in BAR_X
    )
    bars = "\n    ".join(
        f'<rect x="{x}" y="34" width="{BAR_W}" height="188" rx="8" fill="url(#steel)"/>\n    '
        f'<rect x="{x + 3.5}" y="40" width="3.5" height="176" rx="1.75" fill="#ffffff" opacity="0.16"/>'
        for x in BAR_X
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">
  <!--
  {comment}

  Generated by packaging/icons/make-icons.py; edit that script, not this
  file. The starburst is a stylized homage, not Anthropic's official mark.
  -->
  <defs>
    <linearGradient id="steel" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0"    stop-color="#5c626c"/>
      <stop offset="0.35" stop-color="#aab1bc"/>
      <stop offset="0.62" stop-color="#7e838d"/>
      <stop offset="1"    stop-color="#4a4f57"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="{ACCENT}" stop-opacity="0.30"/>
      <stop offset="1" stop-color="{ACCENT}" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <rect x="8" y="8" width="240" height="240" rx="52" fill="#1b1c1e"/>
  <rect x="8.75" y="8.75" width="238.5" height="238.5" rx="51.25" fill="none" stroke="#33353a" stroke-width="1.5"/>

  <!-- the cell behind the prisoner -->
  <rect x="34" y="34" width="188" height="188" rx="24" fill="#101113"/>
  <circle cx="128" cy="128" r="88" fill="url(#glow)"/>

  <!-- the Claude mark -->
  <g fill="{ACCENT}">
    {blades}
  </g>

  <!-- bars: shadows first, so they fall across the mark and not the frame -->
  <g>
    {shadows}
  </g>
  <g>
    {bars}
  </g>

  <!-- top and bottom rails -->
  <rect x="34" y="34" width="188" height="14" rx="7" fill="url(#steel)"/>
  <rect x="34" y="208" width="188" height="14" rx="7" fill="url(#steel)"/>
{badge}</svg>
"""


REVIEW_BADGE = f"""
  <!-- review badge: a magnifying glass over the lower-right corner -->
  <g>
    <circle cx="186" cy="186" r="58" fill="#1b1c1e" stroke="#33353a" stroke-width="1.5"/>
    <line x1="203" y1="203" x2="222" y2="222" stroke="{REVIEW_ACCENT}" stroke-width="16" stroke-linecap="round"/>
    <circle cx="178" cy="178" r="30" fill="#101113" stroke="{REVIEW_ACCENT}" stroke-width="12"/>
    <path d="M 164 172 Q 170 160 182 158" fill="none" stroke="#ffffff" stroke-width="5" stroke-linecap="round" opacity="0.35"/>
  </g>
"""

ICONS = {
    "aio-boxes.svg": cell(
        "AI Orchestrator app icon: the Claude mark behind bars. A box is a cell\n"
        "  you put an agent in."
    ),
    "aio-review.svg": cell(
        "AI Orchestrator Review app icon: the boxes icon with a magnifying glass\n"
        "  badge, so the two apps read as a pair but stay distinct.",
        REVIEW_BADGE,
    ),
}

if __name__ == "__main__":
    here = pathlib.Path(__file__).resolve().parent
    for name, svg in ICONS.items():
        (here / name).write_text(svg)
        print(f"wrote {name}")
